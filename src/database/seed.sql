-- =============================================================================
-- Application seed data.
--
-- This file inserts:
--   1. The classification lookup rows for `Categories`, `StatePowers`, and
--      `Sectors`. These are the controlled vocabularies referenced by
--      `Institutions` through foreign keys (`CategoryId`, `StatePowerId`,
--      `SectorId`).
--   2. The initial Institution records derived from the external reference
--      spreadsheet `resources/ListaEntidadesGubernamentales.xlsx`.
--   3. Five development users (`admin`, `user`, `analista`, `solicitante1`,
--      `solicitante2`) used to exercise JWT-based authentication and
--      role-based authorization during local development.
--
-- The XLSX is treated as a source artifact only. It is NOT parsed at runtime
-- by the application; its contents have been converted to deterministic SQL
-- statements so that database execution remains reproducible and does not
-- depend on Office file libraries.
--
-- Execution order:
--   1. `schema.sql` creates the `dbo.Categories`, `dbo.StatePowers`,
--      `dbo.Sectors`, `dbo.Institutions`, and `dbo.Users` tables and
--      their indexes, foreign keys, and constraints.
--   2. This file (`seed.sql`) populates the lookup tables and inserts the
--      initial data.
--
-- Idempotency:
--   Each classification lookup row is inserted only when no row with the same
--   `Name` already exists (each lookup table has a unique index on `Name`).
--   Each institutional record is inserted only when no row with the same
--   `Name` already exists (the table has a unique index on `Name`). Each
--   user is inserted only when no row with the same `Username` already
--   exists (the table has a unique index on `Username`). Running the script
--   multiple times is safe and will not produce duplicates.
--
-- Identifier and timestamp strategy:
--   * `Id` columns are generated by SQL Server with `NEWID()`, matching the
--     surrogate `Guid` strategy used by the domain entities.
--   * `CreatedAt` is omitted from the insert and relies on the column default
--     `GETUTCDATE()`, matching the EF Core configuration.
--   * Each `Institutions` row resolves its foreign keys through correlated
--     `SELECT` subqueries against the classification lookup tables, so the
--     foreign key identifiers are derived from the canonical `Name` values
--     without hard-coding their `NEWID()` values into the script.
--
-- Data integrity:
--   * Spanish characters (accents, `ñ`, `¿`, `¡`, etc.) are preserved
--     verbatim.
--   * Embedded straight double quotes (for example in
--     `Jardín Botánico Nacional "Dr. Rafael M. Moscoso"`) and typographic
--     curly double quotes are stored as ordinary characters; the values are
--     wrapped in single-quoted string literals with the Unicode prefix `N`.
--   * The dataset contains 181 records with 7 distinct categories, 1 distinct
--     state power, and 25 distinct sectors.
--
-- Password storage:
--   * Plaintext passwords are NEVER stored. The `PasswordHash` columns
--     contain PBKDF2(SHA256, 100,000 iterations, 16-byte salt, 32-byte hash)
--     encoded as `{iterations}.{base64Salt}.{base64Hash}`.
--   * The development credentials below are intentionally weak and MUST NOT
--     be reused in any non-development environment. Replace them via the
--     identity administration flow whenever one is introduced.
--
-- The complete source mapping is:
--   XLSX `Nombre`           -> `Institutions.Name`
--   XLSX `Categoría`        -> `Categories.Name` (referenced by `CategoryId`)
--   XLSX `Poder del Estado` -> `StatePowers.Name` (referenced by `StatePowerId`)
--   XLSX `Sector`           -> `Sectors.Name` (referenced by `SectorId`)
-- =============================================================================

